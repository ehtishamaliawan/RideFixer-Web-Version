import 'ebike_error_model.dart';

class BrandErrorCatalog {
  static List<EbikeErrorInfo> getErrorsByBrand(String brand) {
    final brandLower = brand.toLowerCase();
    final Object errorCodes;

    switch (brandLower) {
      case 'bosch':
        errorCodes = _boschErrorCodes;
        break;
      case 'yamaha':
        errorCodes = _yamahaErrorCodes;
        break;
      case 'shimano':
        errorCodes = _shimanoErrorCodes;
        break;
      case 'bafang':
        errorCodes = _bafangErrorCodes;
        break;
      case 'brose':
        errorCodes = _broseErrorCodes;
        break;
      case 'generic':
        errorCodes = _genericErrorCodes;
        break;
      default:
        return [];
    }

    final items = switch (errorCodes) {
      final List list => list
          .whereType<Map<String, dynamic>>()
          .map((raw) {
            final code = (raw['code'] as String?)?.trim() ?? '';
            return _fromConfig(code: code, raw: raw);
          })
          .where((e) => e.code.isNotEmpty)
          .toList(),
      final Map<String, Map<String, dynamic>> map => map.entries.map((e) => _fromConfig(code: e.key, raw: e.value)).toList(),
      _ => <EbikeErrorInfo>[],
    };

    items.sort((a, b) => a.code.compareTo(b.code));
    return items;
  }

  static EbikeErrorInfo? findByCodeAndBrand(String code, String brand, {String? modelId}) {
    final errors = getErrorsByBrand(brand);
    final normalizedCode = code.trim().toUpperCase();
    final normalizedModel = modelId?.trim().toLowerCase();
    try {
      final matches = errors.where((e) => e.code.toUpperCase() == normalizedCode).toList(growable: false);
      if (matches.isEmpty) return null;

      if (normalizedModel != null && normalizedModel.isNotEmpty) {
        try {
          return matches.firstWhere((e) => e.models.contains(normalizedModel));
        } catch (_) {
          // fall through
        }

        try {
          return matches.firstWhere((e) => e.models.isEmpty);
        } catch (_) {
          // fall through
        }
      }

      return matches.first;
    } catch (_) {
      return null;
    }
  }

  static EbikeErrorInfo _fromConfig({required String code, required Map<String, dynamic> raw}) {
    final title = (raw['title'] as String?)?.trim() ?? 'Error $code';
    final description = (raw['description'] as String?)?.trim() ?? 'Details for this code are not available.';

    final sevStr = (raw['severity'] as String?)?.toLowerCase().trim();
    final severity = switch (sevStr) {
      'high' => EbikeSeverity.high,
      'medium' => EbikeSeverity.medium,
      _ => EbikeSeverity.low,
    };

    final whatItMeans = (raw['whatItMeans'] as String?)?.trim() ?? description;
    final commonCauses = (raw['causes'] as List?)?.whereType<String>().toList() ?? [];
    final commonSymptoms = (raw['symptoms'] as List?)?.whereType<String>().toList() ?? [];
    final howToFix = (raw['fix'] as List?)?.whereType<String>().toList() ?? [];

    final rawModels = raw['models'];
    final models = switch (rawModels) {
      final String single => [single],
      final List list => list.whereType<String>().toList(),
      _ => const <String>[],
    }
        .map((e) => e.toLowerCase().trim())
        .where((e) => e.isNotEmpty)
        .toList(growable: false);

    final rideability = (raw['rideability'] as String?)?.toLowerCase().trim();
    final rideState = switch (rideability) {
      'safe' || 'ok' => Rideability.ok,
      'caution' => Rideability.caution,
      _ => Rideability.stop,
    };

    final urgency = (raw['urgency'] as String?)?.toLowerCase().trim();
    final urgencyLevel = switch (urgency) {
      'immediate' => ServiceUrgency.immediate,
      'soon' => ServiceUrgency.soon,
      _ => ServiceUrgency.info,
    };

    return EbikeErrorInfo(
      code: code,
      title: title,
      description: description,
      severity: severity,
      models: models,
      whatItMeans: whatItMeans,
      commonCauses: commonCauses,
      commonSymptoms: commonSymptoms,
      howToFix: howToFix,
      rideability: rideState,
      rideabilityGuidance: (raw['rideabilityGuidance'] as String?)?.trim() ?? '',
      urgency: urgencyLevel,
      urgencyGuidance: (raw['urgencyGuidance'] as String?)?.trim() ?? '',
    );
  }
}

